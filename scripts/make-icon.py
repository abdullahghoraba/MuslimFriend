# Builds every app icon from the owner's design, images/icon.png (1254 px: a gold open book with three bars over the
# name «الأُنس بالله», on dark green).
#
#   store-assets/icon-512.png                       the Play Store icon: the whole design, name included
#   android/.../mipmap-*/ic_launcher_foreground.png  adaptive icon foreground (and monochrome): the symbol alone, in
#                                                    the safe zone (the launcher prints the name under the icon)
#   android/.../drawable/ic_launcher_background.xml  adaptive icon background: the design's green, as a soft radial
#   android/.../values/ic_launcher_background.xml    that green as a colour (splash screen, theme)
#   android/.../mipmap-*/ic_launcher(_round).png     legacy launcher icons (rounded square / circle)
#   public/assets/studio/logo.png                    the logo drawn in the corner of studio videos
#
# Usage: py -3 scripts/make-icon.py   (needs Pillow and numpy)
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'images' / 'icon.png'
RES = ROOT / 'android' / 'app' / 'src' / 'main' / 'res'

CENTER = (6, 84, 74)   # the design's green, lighter in the middle
EDGE = (1, 60, 58)     # and at its edges
BG = '#03483F'         # one colour for the splash screen and theme

src = Image.open(SRC).convert('RGB')
px = np.asarray(src).astype(np.float32)

# The gold, as coverage: the green has red near 0, the gold about 235.
alpha = np.clip((px[:, :, 0] - 12) / (225 - 12), 0, 1)
# Gold colour without the green mixed into its anti-aliased edges.
green = np.array(EDGE, np.float32)
safe = np.maximum(alpha, 1e-3)[:, :, None]
gold = np.clip((px - (1 - alpha[:, :, None]) * green) / safe, 0, 255)
rgba = np.dstack([gold, alpha * 255]).astype(np.uint8)

# The symbol: the open book and the three bars, above the name (the hamza of «الأُنس» reaches up beside the
# book's right wing, below it: cleared first).
rgba[700:, 890:, 3] = 0
gold_layer = Image.fromarray(rgba)
symbol = gold_layer.crop((190, 230, 1064, 740))
bbox = symbol.getbbox()
symbol = symbol.crop(bbox)


def background(size: int) -> Image.Image:
    """The design's green as a radial gradient (lighter towards the upper middle)."""
    y, x = np.mgrid[0:size, 0:size].astype(np.float32)
    d = np.sqrt((x - size / 2) ** 2 + (y - size * 0.4) ** 2) / (size * 0.75)
    t = np.clip(d, 0, 1)[:, :, None]
    c = np.array(CENTER, np.float32) * (1 - t) + np.array(EDGE, np.float32) * t
    return Image.fromarray(c.astype(np.uint8))


def foreground(size: int) -> Image.Image:
    """The symbol centred in the 108-unit adaptive canvas, inside the 66-unit safe circle."""
    canvas = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    w, h = symbol.size
    diag = (w * w + h * h) ** 0.5
    scale = (size * 62 / 108) / diag
    sw, sh = max(1, round(w * scale)), max(1, round(h * scale))
    s = symbol.resize((sw, sh), Image.LANCZOS)
    canvas.alpha_composite(s, ((size - sw) // 2, round(size * 0.5 - sh * 0.5)))
    return canvas


def masked(img: Image.Image, shape: str) -> Image.Image:
    size = img.size[0]
    big = size * 4
    m = Image.new('L', (big, big), 0)
    d = ImageDraw.Draw(m)
    if shape == 'circle':
        d.ellipse((0, 0, big - 1, big - 1), fill=255)
    else:
        d.rounded_rectangle((0, 0, big - 1, big - 1), radius=big * 0.22, fill=255)
    out = img.convert('RGBA')
    out.putalpha(m.resize((size, size), Image.LANCZOS))
    return out


def legacy(size: int) -> Image.Image:
    """The adaptive icon as a launcher shows it: the middle 72 of 108 units."""
    full = round(size * 108 / 72)
    icon = background(full).convert('RGBA')
    icon.alpha_composite(foreground(full))
    cut = (full - size) // 2
    return icon.crop((cut, cut, cut + size, cut + size))


DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
for name, k in DENSITIES.items():
    folder = RES / f'mipmap-{name}'
    foreground(round(108 * k)).save(folder / 'ic_launcher_foreground.png', optimize=True)
    icon = legacy(round(48 * k))
    masked(icon, 'square').save(folder / 'ic_launcher.png', optimize=True)
    masked(icon, 'circle').save(folder / 'ic_launcher_round.png', optimize=True)

(RES / 'drawable' / 'ic_launcher_background.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-icon.py: the green of images/icon.png. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient android:type="radial" android:gradientRadius="81dp" android:centerX="0.5" android:centerY="0.4"
        android:startColor="#{CENTER[0]:02X}{CENTER[1]:02X}{CENTER[2]:02X}" android:endColor="#{EDGE[0]:02X}{EDGE[1]:02X}{EDGE[2]:02X}"/>
</shape>
''', encoding='utf-8')
(RES / 'values' / 'ic_launcher_background.xml').write_text(
    f'<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">{BG}</color>\n</resources>\n',
    encoding='utf-8')
for name in ('ic_launcher', 'ic_launcher_round'):
    (RES / 'mipmap-anydpi-v26' / f'{name}.xml').write_text('''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
''', encoding='utf-8')

src.resize((512, 512), Image.LANCZOS).save(ROOT / 'store-assets' / 'icon-512.png', optimize=True)
logo = legacy(512)
logo.convert('RGB').save(ROOT / 'public' / 'assets' / 'studio' / 'logo.png', optimize=True)
print('icons written from', SRC.relative_to(ROOT))
